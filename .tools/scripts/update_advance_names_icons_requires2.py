"""Rematch icons and prerequisites for mod advances against vanilla EU5 advances.

Policy
  * theme   - each advance's modifiers are classified into a thematic family
              (military, naval, economy, administration, diplomacy, culture,
              estate, subject) and both its icon and its prerequisite are
              drawn from that family.
  * age     - a prerequisite is ALWAYS a basic advance of the SAME age;
              cross-age chains never happen (pure vanilla has none either).
  * basic   - "basic" means a generic root of that age's tree: no prerequisite
              of its own and no gate (`potential`, `government`, `religion`,
              `culture`, `has_or_had_tag`, `has_variable`, ...), nor any
              ancestor carrying one. Focus-pick advances (gated on
              `has_variable = abm_focus_*`) are therefore never prerequisites.
              A root of the same family wins; otherwise the shallowest root of
              the age is used.
  * units   - the one exception: an advance that unlocks a mod unit takes the
              prerequisite of the vanilla advance unlocking the REGULAR unit
              of the same type and age (see STOCK_UNIT_REQUIRES), so the
              custom unit sits on the same row of the tech tree as its stock
              counterpart instead of behind a generic root.
  * icons   - an icon may appear only once per advance set (per `potential`
              block), checked against the file's existing icons as well as the
              ones assigned during the run; the least-used icon overall is
              preferred. An already-unique icon is left alone unless --force.
  * focus   - abm_focus_picks_*.txt are generated by
              focus_picks/generate_focus_picks.js and skipped by default.

Reference data (--dir, default .tools/eu5/advances)
  *_advances_template.txt   six ages + shape of a tag advance; required
  [0-3]_*.txt               vanilla advances scanned into the reference table

Inputs (positional, mixable and repeatable)
  file path      update that file
  advance key    update only that advance, e.g. abm_bng_combat_piracy
  3-letter tag   update advances whose potential contains has_or_had_tag TAG
Without positional arguments every abm_*.txt in in_game/common/advances runs.

Actions: --icons, --requires, neither = both. --force rewrites unchanged
values. --skip-key/--skip-pattern/--skip-tag/--skip-replace exclude advances.
Written files stay UTF-8 with BOM; existing LF/CRLF endings are preserved.

Examples
  python .tools/scripts/update_advance_names_icons_requires2.py --dry-run
  python .tools/scripts/update_advance_names_icons_requires2.py --icons BNG abm_india_bengal.txt
  python .tools/scripts/update_advance_names_icons_requires2.py --requires abm_bng_combat_piracy
"""

