# ── Text helpers ───────────────────────────────────────────────────
_STRIP_RE = re.compile(r'"[^"]*"|#.*')


def strip_line(line):
    """Drop '#' comments and double-quoted strings from one line."""
    return _STRIP_RE.sub('', line)


def find_top_level_blocks(text):
    """Yield (key, start, end) for every top-level `key = { ... }` block.

    Comment- and string-aware, so braces inside comments or strings never
    disturb block detection.
    """
    depth, key, start = 0, None, None
    for match in re.finditer(r'[^\n]*(?:\n|$)', text):
        code = strip_line(match.group(0))
        depth += code.count('{') - code.count('}')
        if key is None:
            km = re.match(r'^((?:REPLACE|INJECT):)?([A-Za-z_]\w*)\s*=\s*\{',
                          code.strip())
            if km:
                key, start = (km.group(1) or '') + km.group(2), match.start()
        elif depth <= 0:
            yield key, start, match.end()
            key = None


def parse_advance_block(block_text, key):
    """Parse one advance block into its age/icon/requires/fields."""
    open_idx = block_text.find('{')
    close_idx = block_text.rfind('}')
    if open_idx == -1 or close_idx <= open_idx:
        body = ''
    else:
        body = block_text[open_idx + 1:close_idx]
    entry = {
        'key': key,
        'age': None,
        'icons': [],
        'requires': [],
        'fields': [],   # (field, value) top-level lines
        'mod_keys': [],  # field names, for MOD_MAP lookup
        'blocks': [],   # top-level nested block names (potential, allow, ...)
    }
    depth = 0
    for raw in body.split('\n'):
        code = strip_line(raw)
        s = code.strip()
        if not s:
            continue
        opens = code.count('{')
        closes = code.count('}')
        if depth == 0:
            if s.endswith('{'):
                # nested block header (potential, allow, ai_weight, ...)
                header = s.split('=', 1)[0].strip().split()[0] if '=' in s else ''
                if header:
                    entry['blocks'].append(header)
                depth += max(opens - closes, 1)
                continue
            if '=' not in s:
                continue
            field, _, value = s.partition('=')
            field = field.strip()
            value = value.strip()
            if field in STRUCTURAL_SKIP:
                if field == 'age':
                    entry['age'] = value
                elif field == 'icon':
                    entry['icons'].append(value)
                elif field == 'requires':
                    entry['requires'].append(value)
                continue
            entry['fields'].append((field, value))
            entry['mod_keys'].append(field.split()[0])
        else:
            depth += opens - closes
    return entry


def potential_signature(block_text, key):
    """Identity of an advance's potential block (for group icon uniqueness)."""
    match = re.search(r'(?m)^\s*potential\s*=\s*\{', block_text)
    if not match:
        return key
    depth = 0
    for index in range(match.end() - 1, len(block_text)):
        ch = block_text[index]
        if ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                return re.sub(r'\s+', '', strip_line(block_text[match.start():index + 1]))
    return key


# ── Reference table ────────────────────────────────────────────────
class Reference:
    def __init__(self, ref_dir):
        self.dir = Path(ref_dir)
        self.table = {}
        self.hub = Counter()
        self.available_icons = set()
        self.ages = []
        self._load_template()
        self._load_advance_files()
        self._resolve_requires_chain()
        self._mark_generic()
        self._count_hubs()

    def _load_template(self):
        template = self.dir / TEMPLATE_NAME
        if not template.is_file():
            raise SystemExit(
                f"Reference template not found: {template}. "
                f"Expected {TEMPLATE_NAME} in the reference directory."
            )
        text = template.read_text(encoding='utf-8-sig')
        ages = {}
        for m in re.finditer(r'\b(age_\d+_\w+)\b', text):
            num = re.search(r'age_(\d+)_', m.group(1))
            if num:
                ages[int(num.group(1))] = m.group(1)
        self.ages = [ages[n] for n in sorted(ages)]

    def _load_advance_files(self):
        files = sorted(p for p in self.dir.glob('*.txt') if p.is_file())
        if not any(REF_FILE_RE.match(p.name) for p in files):
            raise SystemExit(
                f"No reference advance files matching [0-3]_*.txt in {self.dir}"
            )
        for filepath in files:
            text = filepath.read_text(encoding='utf-8-sig')
            # icons from every *.txt in the dir, not just the [0-3] mask
            self.available_icons.update(
                re.findall(r'(?m)^\s*icon\s*=\s*(\S+)', text)
            )
            if not REF_FILE_RE.match(filepath.name):
                continue
            for key, start, end in find_top_level_blocks(text):
                entry = parse_advance_block(text[start:end], key)
                entry['type'] = None
                entry['known'] = False
                entry['gates'] = sorted(
                    (set(entry['blocks']) & GATE_BLOCKS)
                    | {field for field, _ in entry['fields']
                       if field in GATE_FIELDS}
                )
                self.table[key] = entry
        if not self.available_icons:
            raise RuntimeError(f"No vanilla icons found in {self.dir}")

        # First classification pass: curated theme, then keywords/effects.
        for entry in self.table.values():
            family = mod_family(entry['mod_keys'])
            if family:
                entry['type'] = FAMILY_TYPE[family]
                entry['known'] = True
            else:
                entry['type'] = classify_by_keywords(entry)
                entry['known'] = entry['type'] is not None
                if entry['type'] is None:
                    entry['type'] = classify_by_effects(entry)
                    entry['known'] = entry['type'] is not None

    def _resolve_requires_chain(self):
        """Propagate types through requires links for unclassified entries."""
        unknown = {
            key for key, entry in self.table.items()
            if not entry['known']
        }
        changed = True
        while changed:
            changed = False
            for key in list(unknown):
                entry = self.table[key]
                for req in entry['requires']:
                    other = self.table.get(req)
                    if other and other['known']:
                        entry['type'] = other['type']
                        entry['known'] = True
                        unknown.discard(key)
                        changed = True
                        break
        # Final fallback for anything still unresolved.
        for key in unknown:
            self.table[key]['type'] = 'military'

    def _count_hubs(self):
        for entry in self.table.values():
            for req in entry['requires']:
                self.hub[req] += 1

    def _mark_generic(self):
        """Flag the advances a prerequisite is allowed to point at.

        An advance is generic when it carries no gate of its own and every
        advance in its `requires` chain is generic too, i.e. any nation can
        reach it. Everything else (national/culture/religion/government/focus
        gated advances) is off limits as a prerequisite.
        """
        def generic(key, seen):
            if key in seen:
                return True
            entry = self.table.get(key)
            if entry is None:
                return False
            if entry['gates']:
                return False
            seen.add(key)
            return all(generic(req, seen) for req in entry['requires'])

        for key, entry in self.table.items():
            entry['generic'] = generic(key, set())

        # Distance from a root, generic advances only (0 = root itself).
        self.depth = {}

        def depth_of(key, seen=None):
            if key in self.depth:
                return self.depth[key]
            entry = self.table.get(key)
            if not entry or not entry.get('generic'):
                return None
            if not entry['requires']:
                self.depth[key] = 0
                return 0
            seen = seen or set()
            if key in seen:
                return None
            seen.add(key)
            child = [depth_of(r, seen) for r in entry['requires']]
            child = [c for c in child if c is not None]
            self.depth[key] = 1 + min(child) if child else None
            return self.depth[key]

        for key in self.table:
            depth_of(key)

        # Basic advances per age AND per type: the generic roots of that type,
        # or - when an age has no root of that type - the shallowest generic
        # advances of that type, so every theme keeps a basic anchor.
        self.generic_by_type = defaultdict(lambda: defaultdict(list))
        for key, entry in self.table.items():
            if not entry.get('generic') or entry['age'] is None:
                continue
            rank = self.depth.get(key)
            if rank is None:
                continue
            self.generic_by_type[entry['age']][entry['type']].append((rank, key))

        self.basic = defaultdict(list)       # age -> allowed prerequisites
        self.basic_type = defaultdict(dict)  # age -> type -> same-theme pool
        for age, by_type in self.generic_by_type.items():
            for type_, items in by_type.items():
                shallowest = min(rank for rank, _ in items)
                pool = sorted(k for rank, k in items if rank == shallowest)
                by_type[type_] = pool
                self.basic_type[age][type_] = pool
                self.basic[age].extend(pool)

    def pool(self, age, type_):
        """Basic advances allowed as prerequisites for (age, type).

        Same theme first; when the age has no generic advance of that theme at
        all, the nearest related theme is used instead (naval->military,
        estate->administration, ...), so matches stay thematic where possible.
        """
        by_type = self.basic_type.get(age, {})
        for candidate in (type_,) + TYPE_FALLBACK.get(type_, ()):
            if by_type.get(candidate):
                return by_type[candidate]
        return self.basic.get(age, [])

    def basic_advances(self, age):
        """Every basic advance of `age`, most-referenced first."""
        return sorted(self.basic.get(age, ()),
                      key=lambda k: (-self.hub.get(k, 0), k))

    def requirement_ok(self, key, age, type_=None):
        """True when `key` is a basic advance usable for (age, type)."""
        if type_ is None:
            return key in self.basic.get(age, ())
        return key in self.pool(age, type_)

    def pick_requires(self, key, type_, age, preferred=None,
                      requires_counts=None):
        """Pick a prerequisite: a BASIC advance of the same age AND theme.

        The pool is the age's basic advances for the advance's own type (roots
        when that type has roots, else its one-step advances; a related theme
        when the age has none). The least-used candidate wins (so
        prerequisites spread), then the curated `preferred` value, then the
        most-referenced one.
        """
        pool = [k for k in self.pool(age, type_) if k != key]
        if not pool:
            return None

        def count(k):
            return (requires_counts.get(k, 0)
                    if requires_counts is not None else 0)

        return sorted(pool, key=lambda k: (count(k),
                                           0 if k == preferred else 1,
                                           -self.hub.get(k, 0), k))[0]


def mod_family(mod_keys):
    """Curated theme (family) for an advance, from its modifier keys."""
    return next((MOD_FAMILY[k] for k in mod_keys if k in MOD_FAMILY), None)


def classify_field(field):
    """Classify a single modifier/effect field name.

    Domain prefixes win first; otherwise each underscore-separated segment is
    matched against the keyword sets (never the advance key, never substring
    matching), so e.g. 'clergy_estate_target_satisfaction' is an estate field
    (segment 'estate') and not administration ('state' is not a segment).
    """
    low = field.lower()
    for prefix, type_ in FIELD_PREFIX_TYPE:
        if low.startswith(prefix):
            return type_
    for seg in low.split('_'):
        if not seg:
            continue
        variants = {seg, seg.rstrip('s')} if seg.endswith('s') else {seg}
        for type_ in TYPE_PRIORITY:
            if variants & SEGMENT_KEYWORDS[type_]:
                return type_
    return None


def classify_by_keywords(entry):
    """Classify an advance from its field names by majority vote.

    Every classifiable field casts one vote; the most common type wins, ties
    broken by TYPE_PRIORITY order. This avoids one odd field (e.g. naval_range
    inside an otherwise trade-oriented advance) hijacking the whole advance.
    """
    votes = Counter()
    for field in entry['mod_keys']:
        type_ = classify_field(field)
        if type_:
            votes[type_] += 1
    if not votes:
        return None
    return max(votes, key=lambda t: (votes[t], -TYPE_PRIORITY.index(t)))


def classify_by_effects(entry):
    for field, _value in entry['fields']:
        if field.startswith('unlock_'):
            what = field[len('unlock_'):]
            if any(w in what for w in ('law', 'government', 'reform', 'parliament')):
                return 'administration'
            if 'building' in what:
                return 'economy'
            if 'ship' in what:
                return 'naval'
            if 'unit' in what or 'levy' in what:
                # `unlock_unit = traditional_galley` is a NAVAL advance: the
                # unlocked unit decides the theme, not the field name.
                value = str(_value).lower()
                if any(w in value for w in (
                        'galley', 'ship', 'cog', 'carrack', 'caravel',
                        'galleon', 'frigate', 'fluyt', 'xebec', 'dromond',
                        'dhow', 'junk', 'barge', 'transport', 'privateer',
                        'indiaman', 'threedecker', 'twodecker', 'brig',
                        'sloop', 'pinnace', 'merchantman', 'galleass',
                        'galiot', 'gunboat', 'corvette', 'clipper',
                        'schooner', 'hoy', 'hulk', 'crayer', 'balinger',
                        'nau', 'carvel', 'maritime')):
                    return 'naval'
                return 'military'
            if 'subject' in what:
                return 'subject'
        if field.startswith(('allow_', 'can_', 'may_', 'enable_')):
            if any(w in field for w in ('coloniz', 'tax')):
                return 'economy'
            if 'subject' in field:
                return 'subject'
            if any(w in field for w in ('law', 'parliament', 'government')):
                return 'administration'
    return None


def classify_entry(entry, ref):
    """Classify an input (mod) advance: its fields, else its requires chain."""
    type_ = classify_by_keywords(entry) or classify_by_effects(entry)
    if type_:
        return type_
    return next((ref.table[r]['type'] for r in entry['requires']
                 if ref.table.get(r, {}).get('known')), 'military')


def get_age_require(age_str, family):
    """Age-appropriate vanilla requires override (old behavior)."""
    match = re.search(r'age_(\d+)_', age_str or '')
    if not match:
        return None
    return AGE_REQUIRES.get(int(match.group(1)), {}).get(family)


def generic_fallback(age_str, ref, type_=None):
    """Most basic advance for the age/theme, when nothing else applies."""
    pool = ref.pool(age_str, type_) if type_ else ref.basic_advances(age_str)
    return sorted(pool, key=lambda k: (-ref.hub.get(k, 0), k))[0] if pool else None


_UNIT_SLOTS = None


def unit_slots():
    """Unit id -> (age, category) for every unit the mod defines."""
    global _UNIT_SLOTS
    if _UNIT_SLOTS is None:
        _UNIT_SLOTS = {}
        for path in sorted(UNIT_TYPE_DIR.glob('*.txt')):
            text = path.read_text(encoding='utf-8-sig')
            for key, start, end in find_top_level_blocks(text):
                fields = dict(re.findall(r'(?m)^\s*(\w+)\s*=\s*(\S+)',
                                         text[start:end]))
                age = fields.get('age', '').strip('"')
                category = fields.get('category')
                match = COPY_FROM_RE.match(fields.get('copy_from', ''))
                if match:
                    age, category = age or match.group(1), category or match.group(2)
                if age and category:
                    _UNIT_SLOTS[key.split(':')[-1]] = (
                        age, category.replace('army_', '')
                    )
    return _UNIT_SLOTS


def stock_unit_require(entry, ref):
    """Stock prerequisite for an advance that unlocks a mod unit.

    A custom unit copies a stock template (`copy_from = a_age_3_discovery_
    heavy_infantry`), so its advance takes the prerequisite of the vanilla
    advance that unlocks the regular unit of that type and age - same row,
    same cost. Returns (advance, (age, category)) or None.
    """
    for field, unit in entry['fields']:
        if field != 'unlock_unit':
            continue
        unit_age, category = unit_slots().get(unit, (None, None))
        for age in (entry['age'], unit_age):
            target = STOCK_UNIT_REQUIRES.get((age, category))
            if target and target in ref.table:
                return target, (age, category)
    return None


# ── Icon picking (same type + same age rules as requirements) ───────
def choose_icon(key, requirement, type_, age, ref, group_icons, icon_counts):
    """Pick an icon for `key`, keeping the advance set free of repeats.

    The prerequisite's icon seeds the pool. TYPE is a hard rule (other types
    are excluded); AGE is only a preference, widened step by step (same age ->
    any age) so a repeat can be avoided. The pick then skips icons already
    used by the advance's own set, prefers the least-used icon overall, and
    breaks ties with a hash of the key so results are stable.
    """
    candidates = [requirement] if requirement else []

    def rank_of(candidate):
        entry = ref.table.get(candidate)
        if entry is None or not entry['known']:
            return 0  # curated/unknown: trusted, treated as same-age
        if entry['type'] != type_:
            return None  # wrong type: excluded (hard rule)
        if age and entry['age'] and entry['age'] != age:
            return 1  # same type, cross-age: allowed only to avoid repeats
        return 0  # same type + same age: preferred

    ranked = {}
    for c in candidates:
        r = rank_of(c)
        if r is not None:
            ranked[c] = r

    # Widen the pool: same-age, same-type vanilla icons first (rank 0), then
    # same-type icons of any age (rank 1), most-required advances first.
    same_age = sorted(
        (
            k for k, e in ref.table.items()
            if e['known'] and e['type'] == type_ and e['icons']
            and (not age or e['age'] == age)
        ),
        key=lambda k: (-ref.hub.get(k, 0), k),
    )
    any_age = sorted(
        (
            k for k, e in ref.table.items()
            if e['known'] and e['type'] == type_ and e['icons']
        ),
        key=lambda k: (-ref.hub.get(k, 0), k),
    )
    for rank, keys, cap in ((0, same_age, 24), (1, any_age, 12)):
        added = 0
        for k in keys:
            if added >= cap:
                break
            icon = ref.table[k]['icons'][0]
            if icon in ranked:
                continue
            ranked[icon] = rank
            added += 1

    pool = [c for c in ranked if c in ref.available_icons]
    if not pool:
        raise ValueError(
            f"No valid icon candidates for {key} ({type_})"
        )
    # Hard rule: an icon may appear only once inside an advance set (group).
    fresh = [c for c in pool if c not in group_icons]
    if fresh:
        pool = fresh

    rotation = int(hashlib.sha256(key.encode()).hexdigest()[:8], 16)
    offset = rotation % len(pool)
    pool = pool[offset:] + pool[:offset]
    return min(
        pool,
        key=lambda icon: (
            icon in group_icons, ranked[icon],
            icon_counts.get(icon, 0), pool.index(icon),
        ),
    )


def seed_icon_counts(filepath, icon_counts):
    """Count existing `icon = ...` values so re-runs avoid reusing them."""
    raw = filepath.read_bytes()
    content = raw.decode('utf-8-sig').replace('\r\n', '\n')
    for match in re.finditer(r'^\s*icon\s*=\s*([A-Za-z_]\w*)', content, re.M):
        icon_counts[match.group(1)] += 1


def seed_group_icons(filepath, used_by_group):
    """Register the icons already used by each advance set (potential block).

    Counts are kept per icon, because a set would collapse two advances that
    already share the same icon into a single entry and make both look unique.
    Seeding makes the one-icon-per-set rule hold for pre-existing duplicates,
    not just for icons this run assigns.
    """
    raw = filepath.read_bytes()
    content = raw.decode('utf-8-sig').replace('\r\n', '\n')
    for key, start, end in find_top_level_blocks(content):
        block = content[start:end]
        entry = parse_advance_block(block, key)
        if not entry['age']:
            continue
        counts = used_by_group[potential_signature(block, key)]
        for icon in entry['icons']:
            counts[icon] += 1


def seed_requires_counts(filepath, requires_counts):
    """Count existing `requires = ...` values so re-runs avoid reusing them."""
    raw = filepath.read_bytes()
    content = raw.decode('utf-8-sig').replace('\r\n', '\n')
    for match in re.finditer(
            r'^\s*requires\s*=\s*([A-Za-z_]\w*)', content, re.M):
        requires_counts[match.group(1)] += 1


# ── File transformation ────────────────────────────────────────────
def transform_file(filepath, ref, options):
    raw = filepath.read_bytes()
    has_bom = raw.startswith(b'\xef\xbb\xbf')
    newline = '\r\n' if b'\r\n' in raw else '\n'
    content = raw.decode('utf-8-sig').replace('\r\n', '\n')

    do_icons = options['icons']
    do_requires = options['requires']
    key_filter = options['keys']
    tag_filter = options['tags']
    dry_run = options['dry_run']
    skip_replace = options['skip_replace']
    skip_keys = options['skip_keys']
    skip_patterns = options['skip_patterns']
    skip_tags = options['skip_tags']
    force = options['force']
    requires_counts = options['requires_counts']

    used_by_group = options['used_by_group']
    icon_counts = options['icon_counts']
    changed = 0
    output_parts = []
    cursor = 0

    for key, start, end in find_top_level_blocks(content):
        block = content[start:end]

        if skip_replace and key.startswith('REPLACE:'):
            continue

        bare_key = key.split(':', 1)[-1]
        if skip_keys and (bare_key in skip_keys or key in skip_keys):
            continue
        if skip_patterns and any(
            pat.search(bare_key) or pat.search(key)
            for pat in skip_patterns
        ):
            continue

        if key_filter and bare_key not in key_filter \
                and key not in key_filter:
            continue
        if tag_filter or skip_tags:
            block_tags = set(
                re.findall(r'has_or_had_tag\s*=\s*([A-Z]{3})', block)
            )
            if tag_filter and not (block_tags & tag_filter):
                continue
            if skip_tags and (block_tags & skip_tags):
                continue

        entry = parse_advance_block(block, key)
        if not entry['age'] and not entry['fields']:
            continue

        family = mod_family(entry['mod_keys'])
        if family:
            type_ = FAMILY_TYPE[family]
        else:
            type_ = classify_entry(entry, ref)
            family = FAMILY_FOR_TYPE[type_]
            print(f"  ! {key}: no curated theme, inferred type '{type_}' "
                  f"from {'/'.join(entry['mod_keys'][:3]) or 'nothing'}")
        # Curated age/theme preference: only breaks ties between equally
        # used candidates, and is ignored unless it is a basic advance.
        requirement = get_age_require(entry['age'], family)
        stock = stock_unit_require(entry, ref) if do_requires else None

        if do_requires and entry['age']:
            if stock:
                # Unit unlock: mirror the stock unit of the same slot instead
                # of the generic root, so both are on the same tree row.
                requirement = stock[0]
            # Keep an existing prerequisite when it already satisfies the
            # hard rules (generic, same age): only offending values are
            # re-pointed, so re-runs are no-ops.
            elif len(entry['requires']) == 1 and ref.requirement_ok(
                    entry['requires'][0], entry['age'], type_):
                requirement = entry['requires'][0]
            else:
                repl = ref.pick_requires(
                    key, type_, entry['age'], requirement, requires_counts,
                )
                if repl:
                    requirement = repl
                # Hard rule: the written prerequisite must be generic and of
                # the advance's own age. Curated values can be stale (gated
                # advance, removed advance, or another age) - verify first.
                if not ref.requirement_ok(requirement, entry['age'], type_):
                    fallback = generic_fallback(entry['age'], ref, type_)
                    if fallback:
                        print(f"  ! {key}: '{requirement}' is not a generic "
                              f"same-age advance -> {fallback}")
                        requirement = fallback
        if do_requires:
            requires_counts[requirement] += 1

        if do_requires and entry['requires'] \
                and entry['requires'] != [requirement]:
            why = f"stock {stock[1][1]}" if stock else type_
            print(f"  ~ {key}: requires -> {requirement} ({why})")

        icon = None
        if do_icons and not entry['age']:
            print(
                f"  ! {key}: skipped icon matching (no age field)"
            )
        elif do_icons:
            signature = potential_signature(block, key)
            counts = used_by_group[signature]
            own = Counter(entry['icons'])
            # icons used by the OTHER advances of this set
            group_icons = {i for i, c in counts.items()
                           if c - own.get(i, 0) > 0}
            current_icon = entry['icons'][0] if len(entry['icons']) == 1 else None
            if current_icon and not force and current_icon not in group_icons:
                # already a valid, non-duplicated icon: leave it alone
                icon = current_icon
            else:
                try:
                    icon = choose_icon(
                        key, requirement, type_, entry['age'], ref,
                        group_icons, icon_counts,
                    )
                except ValueError as exc:
                    print(f"  ! {key}: {exc}")
                    icon = None

        if do_icons and icon is not None:
            if entry['icons'] and icon not in entry['icons']:
                print(f"  ~ {key}: icon -> {icon} ({type_})")
            elif not entry['icons']:
                print(f"  + {key}: icon = {icon} ({type_})")

        lines = block.split('\n')
        new_lines = []
        icon_written = req_written = False
        had_icon = any(l.strip().startswith('icon = ') for l in lines)
        had_requires = any(l.strip().startswith('requires = ') for l in lines)
        for line in lines:
            s = line.strip()
            indent = line[:len(line) - len(line.lstrip())]
            # a repeated icon/requires line is dropped, the first one wins
            if do_icons and icon is not None and s.startswith('icon = '):
                if not icon_written:
                    keep = not force and icon in entry['icons']
                    new_lines.append(line if keep else f'{indent}icon = {icon}')
                    icon_written = True
                continue
            if do_requires and s.startswith('requires = '):
                if not req_written:
                    keep = not force and entry['requires'] == [requirement]
                    new_lines.append(
                        line if keep else f'{indent}requires = {requirement}'
                    )
                    req_written = True
                continue
            new_lines.append(line)
            if s.startswith('age = '):
                if do_icons and icon is not None and not had_icon:
                    new_lines.append(f'{indent}icon = {icon}')
                    had_icon = True
                if do_requires and not req_written and not had_requires:
                    new_lines.append(f'{indent}requires = {requirement}')
                    req_written = True

        new_block = '\n'.join(new_lines)

        output_parts.extend((content[cursor:start], new_block))
        cursor = end
        if do_icons and icon is not None:
            signature = potential_signature(block, key)
            counts = used_by_group[signature]
            # the block's previous icon no longer occupies the set
            for old_icon in entry['icons']:
                if counts[old_icon] > 0:
                    counts[old_icon] -= 1
            counts[icon] += 1
            icon_counts[icon] += 1
        changed += 1

    output_parts.append(content[cursor:])
    content = ''.join(output_parts)
    if not dry_run:
        # Repo convention: all files must be UTF-8 with BOM. Always write a
        # BOM, adding one when it was missing.
        output = content.replace('\n', newline).encode('utf-8')
        if content:
            output = b'\xef\xbb\xbf' + output
        filepath.write_bytes(output)
    mode = 'DRY-RUN' if dry_run else 'Done'
    if not content:
        bom_note = 'empty'
    elif has_bom:
        bom_note = 'BOM ok'
    else:
        bom_note = 'BOM ' + ('missing (would add)' if dry_run else 'ADDED')
    print(f'{mode}: {filepath} ({changed} advances processed; {bom_note})')


# ── CLI ────────────────────────────────────────────────────────────
def resolve_targets(targets):
    files, keys, tags = [], set(), set()
    for target in targets:
        path = Path(target)
        if path.suffix == '.txt' and path.is_file():
            files.append(path.resolve())
        elif re.fullmatch(r'[A-Z]{3}', target):
            tags.add(target)
        else:
            keys.add(target)
    return files, keys, tags


CLI_FLAGS = (
    ('--icons', 'store_true', None, 'match icons only'),
    ('--requires', 'store_true', None, 'match prerequisites only'),
    ('--dry-run', 'store_true', None, 'report changes without writing files'),
    ('--skip-replace', 'store_true', None, 'skip keys starting with REPLACE:'),
    ('--skip-key', 'append', 'KEY', 'skip advances with this exact key'),
    ('--skip-pattern', 'append', 'REGEX', 'skip keys matching this regex'),
    ('--skip-tag', 'append', 'TAG', 'skip advances gated on this 3-letter tag'),
    ('--force', 'store_true', None, 'rewrite values even when unchanged'),
)


def build_parser():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        'targets', nargs='*',
        help='files, advance keys, or 3-letter country tags (see docstring)',
    )
    parser.add_argument(
        '--dir', default=str(DEFAULT_REF_DIR),
        help='reference directory (default: %(default)s)',
    )
    for flag, action, metavar, help_text in CLI_FLAGS:
        kwargs = {'action': action, 'help': help_text}
        if metavar:
            kwargs.update(default=[], metavar=metavar,
                          help=help_text + ' (repeatable)')
        parser.add_argument(flag, **kwargs)
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)

    try:
        skip_patterns = [re.compile(p) for p in args.skip_pattern]
    except re.error as exc:
        raise SystemExit(f'Invalid --skip-pattern regex: {exc}')

    do_icons = args.icons or not args.requires
    do_requires = args.requires or not args.icons

    files, keys, tags = resolve_targets(args.targets)
    if not files:
        # abm_focus_picks_*.txt are generated from focus_picks/focus_data.js and
        # their chains are intra-branch by design, so they are not rewritten
        # here; pass such a file explicitly to process it.
        files = [p for p in sorted(ADVANCE_DIR.glob('abm_*.txt'))
                 if 'focus_picks' not in p.name]
    if not files:
        raise SystemExit('No files to process and no abm_*.txt found in '
                         f'{ADVANCE_DIR}')

    ref = Reference(args.dir)
    by_type = Counter(e['type'] for e in ref.table.values())
    print(f"Reference table: {len(ref.table)} vanilla advances "
          f"from {ref.dir} ({len(ref.available_icons)} known icons)")
    print(f"Ages: {', '.join(ref.ages) or '(none parsed from template)'}")
    print("Types: " + ', '.join(
        f"{type_}={by_type[type_]}" for type_ in TYPE_PRIORITY
        if by_type[type_]
    ))
    print(f"Actions: icons={'yes' if do_icons else 'no'}, "
          f"requires={'yes' if do_requires else 'no'}")
    for label, values in (
        ('Advance filter', sorted(keys)),
        ('Tag filter', sorted(tags)),
        ('Skip keys', sorted(set(args.skip_key))),
        ('Skip patterns', args.skip_pattern),
        ('Skip tags', sorted({t.upper() for t in args.skip_tag})),
    ):
        if values:
            print(f"{label}: {', '.join(values)}")
    print()

    options = {
        'icons': do_icons,
        'requires': do_requires,
        'keys': keys or None,
        'tags': tags or None,
        'dry_run': args.dry_run,
        'skip_replace': args.skip_replace,
        'skip_keys': set(args.skip_key),
        'skip_patterns': skip_patterns,
        'skip_tags': {t.upper() for t in args.skip_tag},
        'force': args.force,
        'icon_counts': Counter(),
        'requires_counts': Counter(),
        'used_by_group': defaultdict(Counter),
    }
    seeders = [seed_icon_counts, seed_group_icons] if do_icons else []
    if do_requires:
        seeders.append(seed_requires_counts)
    for filepath in files:
        if do_icons:
            seed_icon_counts(filepath, options['icon_counts'])
            seed_group_icons(filepath, options['used_by_group'])
        if do_requires:
            seed_requires_counts(filepath, options['requires_counts'])
        transform_file(filepath, ref, options)

    print(f"\nProcessed {len(files)} files; most-used icon appears "
          f"{max(options['icon_counts'].values(), default=0)} times")


if __name__ == '__main__':
    main(sys.argv[1:])
